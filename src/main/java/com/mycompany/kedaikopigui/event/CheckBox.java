    private void hitungTotal() {
    int hargaDasar = 25000;
    int total = hargaDasar;

    if (cbGulaAren.isSelected()) {
        total += 3000;
    }
    if (cbSusuOat.isSelected()) {
        total += 5000;
    }
    if (cbExtraShot.isSelected()) {
        total += 4000;
    }
    if (cbEsBatu.isSelected()) {
        total += 1000;
    }

    // Format angka ke format ribuan Indonesia
    lblTotal.setText(String.format("Total :  Rp. %,d", total).replace(',', '.'));
}

